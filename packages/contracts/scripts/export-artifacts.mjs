#!/usr/bin/env node
// Writes src/artifacts.ts from the Hardhat build output (run `hardhat build` first; `pnpm build` does both).
// The output is deterministic: running it twice on the same build produces the same file.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { keccak256 } from 'viem';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTRACTS = ['ElymumArena', 'ElymumNFT', 'TestToken'];

function load(name) {
  const path = join(root, 'artifacts', 'contracts', `${name}.sol`, `${name}.json`);
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(path, 'utf8'));
  } catch (err) {
    throw new Error(`Missing artifact for ${name} (${path}). Run \`pnpm hardhat build\` first.\n${err.message}`);
  }
  const buildInfo = JSON.parse(
    readFileSync(join(root, 'artifacts', 'build-info', `${artifact.buildInfoId}.json`), 'utf8'),
  );
  if (Object.keys(artifact.immutableReferences ?? {}).length > 0) {
    throw new Error(`${name} has immutable variables: its runtime code would differ per deployment.`);
  }
  if (Object.keys(artifact.linkReferences ?? {}).length > 0) {
    throw new Error(`${name} needs library linking, which is not supported.`);
  }
  if (!/^0x[0-9a-f]+$/.test(artifact.bytecode) || !/^0x[0-9a-f]+$/.test(artifact.deployedBytecode)) {
    throw new Error(`${name}: unexpected bytecode format.`);
  }
  return {
    contractName: artifact.contractName,
    sourceName: artifact.sourceName,
    compiler: buildInfo.solcLongVersion,
    evmVersion: buildInfo.input.settings.evmVersion,
    abi: artifact.abi,
    bytecode: artifact.bytecode,
    runtimeCodeHash: keccak256(artifact.deployedBytecode),
  };
}

const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);

let out = `// Generated by scripts/export-artifacts.mjs. Do not edit by hand.
// Regenerate with \`pnpm -F @elymum/contracts build\` (hardhat build + export) after any Solidity change.

/** keccak256 of the runtime code is pinned: these contracts have no immutable variables. */
export interface ElymumArtifact<TAbi> {
  readonly contractName: string;
  readonly sourceName: string;
  /** Full solc version, e.g. 0.8.28+commit.7893614a */
  readonly compiler: string;
  readonly evmVersion: string;
  readonly abi: TAbi;
  /** Creation bytecode (constructor arguments are appended ABI-encoded). */
  readonly bytecode: \`0x\${string}\`;
  /** keccak256 of the deployed runtime bytecode (\`eth_getCode\`). */
  readonly runtimeCodeHash: \`0x\${string}\`;
}
`;

for (const name of CONTRACTS) {
  const a = load(name);
  const id = lowerFirst(name);
  out += `
export const ${id}Abi = ${JSON.stringify(a.abi, null, 2)} as const;

export const ${id}Artifact: ElymumArtifact<typeof ${id}Abi> = {
  contractName: ${JSON.stringify(a.contractName)},
  sourceName: ${JSON.stringify(a.sourceName)},
  compiler: ${JSON.stringify(a.compiler)},
  evmVersion: ${JSON.stringify(a.evmVersion)},
  abi: ${id}Abi,
  bytecode: '${a.bytecode}',
  runtimeCodeHash: '${a.runtimeCodeHash}',
};
`;
}

out += `
export const artifacts = {
${CONTRACTS.map((n) => `  ${n}: ${lowerFirst(n)}Artifact,`).join('\n')}
} as const;

export type ElymumContractName = keyof typeof artifacts;
`;

writeFileSync(join(root, 'src', 'artifacts.ts'), out);
console.log(`src/artifacts.ts: ${CONTRACTS.join(', ')}`);
for (const n of CONTRACTS) console.log(`  ${n} runtimeCodeHash ${load(n).runtimeCodeHash}`);
